<?php

namespace Dgtlss\Clearance\Matrix;

use Dgtlss\Clearance\Diff\ApprovalStore;

final class MarkdownRenderer
{
    public function render(array $matrix): string
    {
        $lines = ['# Clearance access matrix', '', 'Generated by dgtlss/clearance. Review and commit this file with clearance.lock.json.', '',
            '✅ allowed · ❌ denied · 🟡 owned only · ⚠️ unverified or error', ''];
        $approvals = new ApprovalStore;
        if (isset($matrix['scope'])) {
            $lines[] = 'Verification includes '.count($matrix['routes']).' of '.count($matrix['inventory']).' registered route-method entries.';
            $lines[] = '';
            foreach ($matrix['scope'] as $name => $values) {
                $lines[] = '- '.$this->escape($name).': '.$this->escape(json_encode($values, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
            }
            if (isset($matrix['coverage_approval'])) {
                $review = $matrix['coverage_approval'];
                $lines[] = '- Scope review'.($approvals->validCoverage($matrix) ? '' : ' (invalid)').': '.$this->escape($review['by'].': '.$review['reason']);
            }
            $lines[] = '';
        }
        $groups = [];

        foreach ($matrix['routes'] as $id => $route) {
            $group = explode('/', trim($route['uri'], '/'))[0] ?: '/';
            $groups[$group][$id] = $route;
        }

        ksort($groups);

        foreach ($groups as $group => $routes) {
            $lines[] = '## '.$this->escape($group);
            $lines[] = '';
            $lines[] = '| Route | Static | '.implode(' | ', array_map($this->escape(...), $matrix['personas'])).' | Approval |';
            $lines[] = '| --- | --- | '.implode(' | ', array_fill(0, count($matrix['personas']), '---')).' | --- |';

            foreach ($routes as $id => $route) {
                $cells = array_map(fn (string $persona) => $this->cell($route['access'][$persona] ?? 'unverified'), $matrix['personas']);
                $approval = $route['approved'] ?? null;
                $lines[] = '| '.$this->escape($id).' | '.$this->escape($route['verdict']).' | '.implode(' | ', $cells).' | '
                    .($approval ? ($approvals->valid($route) ? '' : 'Invalid: ').$this->escape(($approval['by'] ?? '?').': '.($approval['reason'] ?? '?'))
                        .(isset($approval['persona']) ? ' ('.$this->escape($approval['persona']).')' : '') : '—').' |';
            }

            $lines[] = '';
        }

        return implode("\n", $lines)."\n";
    }

    public function cell(string|array $access): string
    {
        if (is_array($access)) {
            if (in_array('error', $access, true) || in_array('unverified', $access, true)) {
                return '⚠️';
            }

            if (($access['owned'] ?? null) === 'allow' && ($access['foreign'] ?? null) === 'deny') {
                return '🟡';
            }

            return in_array('allow', $access, true) ? '✅' : '❌';
        }

        return match ($access) {
            'allow' => '✅',
            'deny' => '❌',
            default => '⚠️',
        };
    }

    private function escape(string $value): string
    {
        return str_replace(["\r", "\n", '|', '<', '>'], [' ', ' ', '\\|', '&lt;', '&gt;'], $value);
    }
}
